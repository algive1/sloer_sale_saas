export function createEditorDictionary(t: OpsTranslator) {
	return Object.fromEntries(
		Object.entries(messages).map(([key, source]) => {
			const values = Object.fromEntries(
				[...source.matchAll(/\{(\w+)\}/g)].map((match) => [match[1], `{${match[1]}}`]),
			);
			return [key, t(source, values)];
		}),
	);
}
